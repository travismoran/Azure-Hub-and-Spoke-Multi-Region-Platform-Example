#!/usr/bin/env python3
"""Render CiliumClusterwideNetworkPolicy manifests from catalog/stamps.json.

Usage: gen-cilium-caller-policies.py <env> <subnets.json> <out-dir>
  subnets.json: {"<stamp-id>": ["<node subnet cidr>", ...], ...}
Output: <out-dir>/<stamp-id>.yaml per target stamp in the catalog.
"""
import json
import pathlib
import sys

LABEL = "platform.demo/callable"


def render(stamp, callers, subnets):
    cidrs = sorted(c for s in callers for c in subnets.get(s, []))
    missing = [s for s in callers if s not in subnets]
    if missing:
        raise SystemExit(f"{stamp}: no node subnets known for caller(s) {missing}")
    lines = [
        "# Generated by scripts/gen-cilium-caller-policies.sh from catalog/stamps.json - do not edit.",
        f"# Target stamp: {stamp}. Callers: {', '.join(callers) or '(none)'}",
        "apiVersion: cilium.io/v2",
        "kind: CiliumClusterwideNetworkPolicy",
        "metadata:",
        f"  name: callers-{stamp}",
        "spec:",
        "  description: Mesh callers allowed to reach callable pods of this stamp",
        "  endpointSelector:",
        "    matchLabels:",
        f'      {LABEL}: "true"',
        "  ingress:",
        "    # Same-cluster traffic is never from a remote node subnet; allow it explicitly",
        "    # so the default deny below applies only to mesh traffic.",
        "    - fromEntities: [cluster]",
    ]
    if cidrs:
        lines.append("    - fromCIDR:")
        lines += [f"        - {c}" for c in cidrs]
    else:
        lines.append("    # No callers allowed: mesh traffic to callable pods is dropped.")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 4:
        raise SystemExit(__doc__)
    env, subnets_file, out_dir = argv[1], pathlib.Path(argv[2]), pathlib.Path(argv[3])
    catalog = json.loads(pathlib.Path("catalog/stamps.json").read_text())
    subnets = json.loads(subnets_file.read_text())
    targets = catalog.get(env)
    if targets is None:
        raise SystemExit(f"environment {env!r} not in catalog/stamps.json")
    out_dir.mkdir(parents=True, exist_ok=True)
    for stamp, spec in sorted(targets.items()):
        (out_dir / f"{stamp}.yaml").write_text(render(stamp, spec.get("allow_from", []), subnets))
        print(f"wrote {out_dir / stamp}.yaml")


if __name__ == "__main__":
    main(sys.argv)
